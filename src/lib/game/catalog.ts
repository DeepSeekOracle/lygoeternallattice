export const CARDS: CardDef[] = Object.entries(ROWS).flatMap(([cid, rows]) =>
  rows.map((r) => rowToCard(cid, r)),
);

function normalizeCopies() {
  const ids = Array.from(new Set(CARDS.map((c) => c.championId)));
  for (const cid of ids) {
    const pool = CARDS.filter((c) => c.championId === cid);
    const total = () => pool.reduce((s, c) => s + c.copies, 0);
    while (total() < 29) {
      const bump = pool.find((c) => c.copies < 2 && c.rarity !== "signature");
      if (bump) {
        bump.copies += 1;
        continue;
      }
      const id = `${cid}-shard-${pool.length}`;
      const shard: CardDef = {
        id,
        name: "Lattice Shard",
        type: "minion",
        championId: cid,
        rarity: "common",
        cost: 2,
        power: 2,
        toughness: 2,
        keywords: [],
        copies: 1,
        onPlay: [],
        onDeath: [],
        onAttack: [],
        text: "A remnant of the seal.",
      };
      CARDS.push(shard);
      pool.push(shard);
    }
    while (total() > 29) {
      const drop = [...pool].reverse().find((c) => c.copies > 1 && c.rarity === "common")
        ?? pool.find((c) => c.copies > 1);
      if (!drop) break;
      drop.copies -= 1;
    }
  }
}
normalizeCopies();

export const CARD_BY_ID: Record<string, CardDef> = Object.fromEntries(CARDS.map((c) => [c.id, c]));
export const CHAMP_BY_ID: Record<string, ChampionDef> = Object.fromEntries(
  CHAMPIONS.map((c) => [c.id, c]),
);

export function defaultList(championId: string): string[] {
  const out: string[] = [];
  for (const c of CARDS) {
    if (c.championId !== championId) continue;
    for (let i = 0; i < c.copies; i++) out.push(c.id);
  }
  return out;
}

export function deckIssues(championId: string): string[] {
  const list = defaultList(championId);
  const issues: string[] = [];
  if (list.length !== 29) issues.push(`${championId} has ${list.length} cards, need 29`);
  const counts: Record<string, number> = {};
  for (const id of list) counts[id] = (counts[id] ?? 0) + 1;
  for (const [id, n] of Object.entries(counts)) {
    if (n > 2) issues.push(`${id} has ${n} copies`);
  }
  return issues;
}

