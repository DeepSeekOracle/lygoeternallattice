import type { CardDef, CardType, ChampionDef, ChampionPassive, Rarity } from "./types";
import { parseFx, parseKw } from "./fx";

type Row = [
  id: string,
  name: string,
  kind: "M" | "S" | "R",
  cost: number,
  p: number,
  t: number,
  kw: string,
  copies: number,
  rarity: Rarity,
  play: string,
  death: string,
  text: string,
];

function rowToCard(championId: string, r: Row): CardDef {
  const type: CardType = r[2] === "M" ? "minion" : r[2] === "R" ? "resonance" : "spell";
  return {
    id: r[0],
    name: r[1],
    type,
    championId,
    rarity: r[8],
    cost: r[3],
    power: r[4],
    toughness: r[5],
    keywords: parseKw(r[6]),
    copies: r[7],
    onPlay: parseFx(r[9]),
    onDeath: parseFx(r[10]),
    onAttack: [],
    text: r[11],
  };
}

function champ(
  partial: Omit<ChampionDef, "ability" | "passive"> & {
    abilityFx: string;
    passive: ChampionPassive;
  },
): ChampionDef {
  return {
    ...partial,
    ability: parseFx(partial.abilityFx),
    passive: partial.passive,
  };
}

